#!/usr/bin/env bash
# 컷오버·롤백 스크립트의 멱등·쓰기 담당 확인·실패 처리를 로컬 Postgres 두 대로 시험한다(인프라 12.1, echo-infra#66).
# 사용: replication/k8s/scripts/tests/run.sh   (Docker 필요. 끝나면 컨테이너를 지운다. KEEP=1 이면 남긴다)
set -uo pipefail
cd "$(dirname "$0")"
T=$PWD; S=$T/..
export STATE=$T/.state PATH="$T/bin:$PATH"
export A_CTX=test-a B_CTX=test-b A_HOST=echo-t-pg-a B_HOST=echo-t-pg-b
exec </dev/null
pass=0 fail=0
ok()   { echo "  ✅ $*"; pass=$((pass+1)); }
bad()  { echo "  ❌ $*"; fail=$((fail+1)); }
check() { local name=$1 want=$2 got=$3; [[ $got == "$want" ]] && ok "$name ($got)" || bad "$name: 기대 '$want', 실제 '$got'"; }
q()    { local c; [[ $1 == A ]] && c=echo-t-pg-a || c=echo-t-pg-b; docker exec -i "$c" psql -X -U postgres -d app -tAq -c "$2"; }
run()  { local out rc; out=$("$@" 2>&1); rc=$?; LAST_OUT=$out; echo "$out" | sed 's/^/     │ /'; return $rc; }
writer() { (source "$S/common.sh"; writer_side) 2>/dev/null; }
pauses() { grep -c 'PAUSE' "$STATE/pgb.log" 2>/dev/null || true; }
cmhost() { sed -n 's/^app = host=\([^ ]*\).*/\1/p' "$STATE/cm_$1.ini"; }
restart() { cp "$STATE/cm_$1.ini" "$STATE/pgb_$1.ini"; }   # 파드 재시작 흉내: copy-ini 가 ConfigMap 을 복사
wait_n() { local side=$1 n=$2 i; for i in $(seq 1 50); do [[ $(q "$side" "SELECT COALESCE(max(n),0) FROM demo.seq_write;") == "$n" ]] && return 0; sleep 0.2; done; return 1; }
P1=11111111-1111-4111-8111-111111111111 P2=22222222-2222-4222-8222-222222222222
P3=33333333-3333-4333-8333-333333333333 P4=44444444-4444-4444-8444-444444444444

cleanup() { [[ ${KEEP:-} == 1 ]] || docker compose down -v >/dev/null 2>&1; }
trap cleanup EXIT

echo "== 준비: Postgres A·B, 계정·발행, PgBouncer ini(A 가 쓰기 담당)"
docker compose down -v >/dev/null 2>&1; docker compose up -d >/dev/null
for c in echo-t-pg-a echo-t-pg-b; do until docker exec "$c" pg_isready -U postgres -d app >/dev/null 2>&1; do sleep 0.5; done; done
sleep 1
for side in A B; do q "$side" "
  CREATE ROLE app_rw LOGIN; CREATE ROLE echo_monitor LOGIN;
  CREATE ROLE repl_user LOGIN REPLICATION PASSWORD 'test'; GRANT pg_read_all_data TO repl_user;
  CREATE SCHEMA demo;
  CREATE TABLE demo.seq_write (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n bigint NOT NULL UNIQUE,
    wrote_at timestamptz NOT NULL DEFAULT now(), written_env text NOT NULL DEFAULT 'unknown');
  CREATE PUBLICATION echo_pub FOR ALL TABLES;" >/dev/null; done
rm -rf "$STATE"; mkdir -p "$STATE"; : > "$STATE/pgb.log"
echo "app = host=echo-pg port=5432 dbname=app" > "$STATE/pgb_A.ini"
echo "app = host=$A_HOST port=5432 dbname=app" > "$STATE/pgb_B.ini"
cp "$STATE/pgb_A.ini" "$STATE/cm_A.ini"; cp "$STATE/pgb_B.ini" "$STATE/cm_B.ini"; : > "$STATE/cm.log"
q A "INSERT INTO demo.seq_write (n) SELECT g FROM generate_series(1, 50) g;" >/dev/null
run "$S/subscribe.sh" >/dev/null || { echo "subscribe.sh 실패"; echo "$LAST_OUT"; exit 1; }
wait_n B 50 && ok "정방향 복제 A→B 초기 복사 50건" || bad "초기 복사"

echo "== 1. 처음 상태의 쓰기 담당"
check "writer_side" A "$(writer)"

echo "== 2. PLAN_ID 형식이 틀리면 아무것도 하지 않는다"
run env PLAN_ID="1'; DROP TABLE demo.seq_write; --" "$S/cutover.sh"; check "종료 코드" 1 $?
check "PAUSE 0회" 0 "$(pauses)"

echo "== 3. A 가 이미 쓰기 담당일 때 rollback.sh → ALREADY_WRITER"
run "$S/rollback.sh"; check "종료 코드" 0 $?
[[ $LAST_OUT == *ALREADY_WRITER* ]] && ok "ALREADY_WRITER 출력" || bad "ALREADY_WRITER 출력 없음"
check "PAUSE 0회" 0 "$(pauses)"

echo "== 4. PLAN_ID=P1 컷오버 A→B"
run env PLAN_ID=$P1 "$S/cutover.sh"; check "종료 코드" 0 $?
check "writer_side" B "$(writer)"
check "B 의 P1 기록 (kind|mode|누락|중복)" "CUTOVER|NORMAL|0|0" "$(q B "SELECT kind||'|'||mode||'|'||missing_rows||'|'||duplicate_rows FROM echo_ops.cutover_runs WHERE plan_id='$P1';")"
sleep 1; check "기록이 A 로 역복제됨" 1 "$(q A "SELECT count(*) FROM echo_ops.cutover_runs WHERE plan_id='$P1';")"
check "PAUSE 2회(A·B)" 2 "$(pauses)"

echo "== 4-1. 컷오버 뒤 ConfigMap 도 새 백엔드 → PgBouncer 파드가 다시 떠도 B 가 쓰기 담당"
check "A ConfigMap 백엔드" "$B_HOST" "$(cmhost A)"
check "B ConfigMap 백엔드" echo-pg "$(cmhost B)"
restart A; restart B
check "재시작 뒤 writer_side" B "$(writer)"

echo "== 5. 같은 PLAN_ID 로 다시 → ALREADY_DONE, 쓰기 정지 없음"
run env PLAN_ID=$P1 "$S/cutover.sh"; check "종료 코드" 0 $?
[[ $LAST_OUT == *ALREADY_DONE* ]] && ok "ALREADY_DONE 출력" || bad "ALREADY_DONE 출력 없음"
check "PAUSE 그대로 2회" 2 "$(pauses)"

echo "== 6. 다른 PLAN_ID 로 다시 컷오버 → ALREADY_WRITER"
run env PLAN_ID=$P2 "$S/cutover.sh"; check "종료 코드" 0 $?
[[ $LAST_OUT == *ALREADY_WRITER* ]] && ok "ALREADY_WRITER 출력" || bad "ALREADY_WRITER 출력 없음"
check "P2 기록 없음" 0 "$(q B "SELECT count(*) FROM echo_ops.cutover_runs WHERE plan_id='$P2';")"

echo "== 7. B 에 쓰고 PLAN_ID=P3 롤백 B→A"
q B "INSERT INTO demo.seq_write (n, written_env) SELECT g, 'gcp' FROM generate_series(51, 60) g;" >/dev/null
wait_n A 60 && ok "역복제 B→A 10건" || bad "역복제"
run env PLAN_ID=$P3 "$S/rollback.sh"; check "종료 코드" 0 $?
check "writer_side" A "$(writer)"
check "A 의 P3 기록 (kind|장부|누락|중복)" "ROLLBACK|60|0|0" "$(q A "SELECT kind||'|'||rows_total||'|'||missing_rows||'|'||duplicate_rows FROM echo_ops.cutover_runs WHERE plan_id='$P3';")"
q A "INSERT INTO demo.seq_write (n) VALUES (61);" >/dev/null
wait_n B 61 && ok "롤백 뒤 정방향 복제 A→B 재개" || bad "정방향 복제 재개"

echo "== 7-1. 롤백 뒤 ConfigMap 도 A 로 → 재시작해도 A 가 쓰기 담당"
check "A ConfigMap 백엔드" echo-pg "$(cmhost A)"
check "B ConfigMap 백엔드" "$A_HOST" "$(cmhost B)"
restart A; restart B
check "재시작 뒤 writer_side" A "$(writer)"

echo "== 8. 쓰기 정지 중(시퀀스 맞춤) 실패 → 종료 1, 양쪽 RESUME, 쓰기 담당 그대로"
: > "$STATE/pgb.log"
run env FAIL_SQL='setval' PLAN_ID=$P4 "$S/cutover.sh"; check "종료 코드" 1 $?
check "RESUME 2회" 2 "$(grep -c RESUME "$STATE/pgb.log")"
check "writer_side" A "$(writer)"

echo "== 9. 전환 도중(역방향 구독 만들기) 실패 → 종료 2, RESUME 안 함, 다음 실행도 2"
: > "$STATE/pgb.log"
run env FAIL_SQL='CREATE SUBSCRIPTION echo_sub_rev' PLAN_ID=$P4 "$S/cutover.sh"; check "종료 코드" 2 $?
check "RESUME 0회" 0 "$(grep -c RESUME "$STATE/pgb.log" || true)"
[[ $(writer) == PARTIAL* ]] && ok "writer_side = PARTIAL" || bad "writer_side: $(writer)"
run env PLAN_ID=$P4 "$S/cutover.sh"; check "부분 상태에서 다시 실행 → 종료 코드" 2 $?

echo "== 10. README '부분 상태 복구' 첫 줄대로 되돌린 뒤 다시 컷오버 → 성공"
(source "$S/common.sh"; pg B -c "ALTER SUBSCRIPTION echo_sub ENABLE;" >/dev/null; pgb A "RESUME app;"; pgb B "RESUME app;")
check "되돌린 뒤 writer_side" A "$(writer)"
q A "INSERT INTO demo.seq_write (n) VALUES (62);" >/dev/null
wait_n B 62 && ok "정방향 복제 다시 흐름" || bad "정방향 복제"
run env PLAN_ID=$P4 "$S/cutover.sh"; check "종료 코드" 0 $?
check "B 의 P4 기록 (장부|누락|중복)" "62|0|0" "$(q B "SELECT rows_total||'|'||missing_rows||'|'||duplicate_rows FROM echo_ops.cutover_runs WHERE plan_id='$P4';")"

echo "== 11. 롤백 뒤 ConfigMap 맞추기 실패 → 종료 2, 같은 명령을 다시 돌리면 맞추고 ALREADY_DONE"
Q1=99999999-9999-4999-8999-999999999999
run env FAIL_CM=A PLAN_ID=$Q1 "$S/rollback.sh"; check "종료 코드" 2 $?
check "쓰기 담당은 A 로 바뀜" A "$(writer)"
check "A ConfigMap 은 아직 옛 값" "$B_HOST" "$(cmhost A)"
run env PLAN_ID=$Q1 "$S/rollback.sh"; check "다시 실행 → 종료 코드" 0 $?
[[ $LAST_OUT == *ALREADY_DONE* ]] && ok "ALREADY_DONE 출력" || bad "ALREADY_DONE 출력 없음"
check "A ConfigMap 맞춰짐" echo-pg "$(cmhost A)"
restart A; restart B
check "재시작 뒤 writer_side" A "$(writer)"

echo; echo "결과: 통과 $pass · 실패 $fail"
[[ $fail == 0 ]]

#!/usr/bin/env bash
# 행 내용·스키마 지문 대조 검증기(content-verify.sh, 인프라 25)를 로컬 Postgres 두 대로 격리 시험한다. 운영 DB 에는 붙지 않는다.
# 사용: replication/k8s/scripts/tests/content-verify-test.sh   (Docker 필요. 끝나면 컨테이너를 지운다. KEEP=1 이면 남긴다)
set -uo pipefail
cd "$(dirname "$0")"
T=$PWD; S=$T/..
export T_PREFIX="${T_PREFIX:-echo-cv}"
export STATE=$T/.state-$T_PREFIX PATH="$T/bin:$PATH" A_CTX=test-a B_CTX=test-b
exec </dev/null
pass=0 fail=0
ok()  { echo "  ✅ $*"; pass=$((pass+1)); }
bad() { echo "  ❌ $*"; fail=$((fail+1)); }
check() { [[ $3 == "$2" ]] && ok "$1 ($3)" || bad "$1: 기대 '$2', 실제 '$3'"; }
q() { local c; [[ $1 == A ]] && c=$T_PREFIX-pg-a || c=$T_PREFIX-pg-b; docker exec -i "$c" psql -X -U postgres -d app -tAq -v ON_ERROR_STOP=1 -c "$2"; }
# cv [환경 변수…] : 검증기 실행. OUT = JSON, RC = 종료 코드
cv() { OUT=$(env "$@" "$S/content-verify.sh" 2>"$STATE/cv.err"); RC=$?; }
res() { python3 -I -c 'import json,sys; d=json.loads(sys.argv[1]); t=[x for x in d["tables"] if x["table"]==sys.argv[2]][0]; print(t["result"]+"/"+(t["reason"] or "-"))' "$OUT" "$1"; }
fp()  { python3 -I -c 'import json,sys; d=json.loads(sys.argv[1]); t=[x for x in d["tables"] if x["table"]==sys.argv[2]][0]; f=t["fingerprints"]; print(f["schema"]["source"],f["primaryKeys"]["source"],f["rows"]["source"])' "$OUT" "$1"; }
wait_eq() { local i; for i in $(seq 1 50); do [[ $(q A "$1") == "$(q B "$1")" ]] && return 0; sleep 0.2; done; return 1; }

cleanup() { [[ ${KEEP:-} == 1 ]] || docker compose down -v >/dev/null 2>&1; }
trap cleanup EXIT
mkdir -p "$STATE"

echo "== 준비: Postgres A(출발)·B(도착), 등록 표 4개 + 지원 밖 표 2개, A→B 논리 복제"
docker compose down -v >/dev/null 2>&1; docker compose up -d >/dev/null
for c in $T_PREFIX-pg-a $T_PREFIX-pg-b; do until docker exec "$c" pg_isready -U postgres -d app >/dev/null 2>&1; do sleep 0.5; done; done
sleep 1
DDL="
CREATE SCHEMA demo; CREATE SCHEMA shop;
CREATE TABLE demo.seq_write (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n bigint NOT NULL UNIQUE,
  wrote_at timestamptz NOT NULL DEFAULT now(), written_env text NOT NULL DEFAULT 'unknown', request_id text);
CREATE TABLE shop.items (id int PRIMARY KEY, name text NOT NULL, price numeric(10,2), note text, attrs jsonb,
  ratio float8, blob bytea, born date, at timestamptz);
CREATE TABLE shop.orders (order_no text, line int, item int NOT NULL, qty int NOT NULL, PRIMARY KEY (order_no, line));
CREATE TABLE demo.geo (id int PRIMARY KEY, p point);
CREATE TABLE demo.nopk (a int, b text);"
q A "$DDL" >/dev/null && q B "$DDL" >/dev/null
q A "CREATE TABLE demo.colorder (id int PRIMARY KEY, a text, b int);" >/dev/null
q B "CREATE TABLE demo.colorder (b int, id int PRIMARY KEY, a text);" >/dev/null   # 열 순서만 다름(복제 대상 아님)
q A "INSERT INTO demo.seq_write (n, request_id) SELECT g, CASE WHEN g % 3 = 0 THEN NULL ELSE 'k'||g END FROM generate_series(1, 300) g;
     INSERT INTO shop.items VALUES
       (1, 'secret-row-value', 12.30, NULL, '{\"b\":1,\"a\":[1,2]}', 0.1, '\\xdeadbeef', '2026-11-08', '2026-11-08 10:00:00+09'),
       (2, '사과', 1.00, '', '{}', 1e-7, NULL, NULL, NULL),
       (3, 'pear', NULL, 'x', NULL, -0.0, '\\x', '1999-12-31', '2000-01-01 00:00:00+00');
     INSERT INTO shop.orders VALUES ('A-10', 1, 1, 2), ('A-9', 1, 2, 1), ('A-9', 2, 3, 5);
     INSERT INTO demo.geo VALUES (1, '(1,2)'); INSERT INTO demo.nopk VALUES (1, 'x');
     CREATE PUBLICATION cv_pub FOR TABLE demo.seq_write, shop.items, shop.orders;" >/dev/null
q B "CREATE SUBSCRIPTION cv_sub CONNECTION 'host=$T_PREFIX-pg-a port=5432 dbname=app user=postgres' PUBLICATION cv_pub;" >/dev/null 2>&1
for side in A B; do q $side "INSERT INTO demo.colorder (id, a, b) VALUES (1, 'x', 1), (2, NULL, NULL);" >/dev/null; done
wait_eq "SELECT count(*) FROM demo.seq_write" && wait_eq "SELECT count(*) FROM shop.orders" && ok "초기 복제 A→B" || bad "초기 복제"
REG="demo.seq_write shop.items shop.orders demo.colorder"
ALL="$REG demo.geo demo.nopk"
TABLES="$ALL" "$S/verify-user.sh" >/dev/null && ok "verify-user.sh: echo_verify 생성(양쪽)" || bad "verify-user.sh"
TABLES="$ALL" "$S/verify-user.sh" >/dev/null && ok "verify-user.sh 다시 실행(멱등)" || bad "verify-user.sh 재실행"

echo "== 1. 같은 데이터 → MATCH (SLOT 으로 따라잡기 확인)"
cv TABLES="$REG" SLOT=cv_sub
check "종료 코드" 0 "$RC"
for t in $REG; do check "$t" MATCH/- "$(res $t)"; done
check "caughtUp" True "$(python3 -I -c 'import json,sys; print(json.loads(sys.argv[1])["alignment"]["caughtUp"])' "$OUT")"
FP1=$(fp shop.items)
cv TABLES="$REG" SLOT=cv_sub; check "같은 입력 → 같은 지문(재현)" "$FP1" "$(fp shop.items)"
check "열 순서만 다른 표 → MATCH" MATCH/- "$(res demo.colorder)"

echo "== 2. 지원 밖 타입·기본 키 없음 → UNKNOWN"
cv TABLES="$ALL"
check "종료 코드(UNKNOWN 있음)" 2 "$RC"
check "demo.geo(point)" UNKNOWN/UNSUPPORTED_TYPE "$(res demo.geo)"
check "demo.nopk" UNKNOWN/NO_PRIMARY_KEY "$(res demo.nopk)"
check "나머지는 그대로 MATCH" MATCH/- "$(res shop.items)"

echo "== 3. 출력에 행 원문이 없다"
[[ $OUT != *secret-row-value* && $(cat "$STATE/cv.err") != *secret-row-value* ]] && ok "행 값 'secret-row-value' 미출력" || bad "행 값이 출력됨"
[[ $OUT != *사과* ]] && ok "행 값 '사과' 미출력" || bad "행 값이 출력됨"

echo "== 4. 조회 계정은 쓰지 못한다"
docker exec -i $T_PREFIX-pg-b psql -X -U echo_verify -d app -tAq -c "INSERT INTO shop.items (id, name) VALUES (99, 'x');" >/dev/null 2>&1 \
  && bad "echo_verify 로 INSERT 가 됐다" || ok "echo_verify INSERT 거부"
docker exec -i $T_PREFIX-pg-b psql -X -U echo_verify -d app -tAq -c "SELECT count(*) FROM pg_authid;" >/dev/null 2>&1 \
  && bad "echo_verify 로 pg_authid 를 읽었다" || ok "echo_verify 등록 밖 표(pg_authid) 거부"
check "echo_verify 기본 읽기 전용" on "$(docker exec -i $T_PREFIX-pg-b psql -X -U echo_verify -d app -tAq -c 'SHOW default_transaction_read_only;')"

echo "== 5. 도착에서 값 하나만 바꿈(행 수·ID 같음) → MISMATCH ROW_CONTENT"
q B "UPDATE shop.items SET price = 12.31 WHERE id = 1;" >/dev/null
cv TABLES="shop.items" SLOT=cv_sub
check "종료 코드" 1 "$RC"; check "shop.items" MISMATCH/ROW_CONTENT "$(res shop.items)"
q B "UPDATE shop.items SET price = 12.30 WHERE id = 1;" >/dev/null
cv TABLES="shop.items" SLOT=cv_sub; check "되돌리면 MATCH" MATCH/- "$(res shop.items)"

echo "== 6. NULL 과 빈 문자열을 구분한다"
q B "UPDATE shop.items SET note = '' WHERE id = 1;" >/dev/null
cv TABLES="shop.items" SLOT=cv_sub; check "NULL → ''" MISMATCH/ROW_CONTENT "$(res shop.items)"
q B "UPDATE shop.items SET note = NULL WHERE id = 1;" >/dev/null

echo "== 7. 누락 행 → ROW_COUNT, 같은 개수인데 다른 키 → PRIMARY_KEYS"
q B "DELETE FROM demo.seq_write WHERE n = 7;" >/dev/null
cv TABLES="demo.seq_write" SLOT=cv_sub; check "누락 1행" MISMATCH/ROW_COUNT "$(res demo.seq_write)"
q B "INSERT INTO demo.seq_write (id, n) VALUES (100000, 100000);" >/dev/null
cv TABLES="demo.seq_write" SLOT=cv_sub; check "개수 같고 키 다름" MISMATCH/PRIMARY_KEYS "$(res demo.seq_write)"

echo "== 8. 스키마 차이 → SCHEMA, 도착에 표 없음 → TARGET_TABLE_MISSING"
q B "ALTER TABLE shop.orders ADD COLUMN memo text;" >/dev/null
cv TABLES="shop.orders" SLOT=cv_sub; check "도착에 열 추가" MISMATCH/SCHEMA "$(res shop.orders)"
q A "CREATE TABLE shop.only_a (id int PRIMARY KEY); GRANT USAGE ON SCHEMA shop TO echo_verify; GRANT SELECT ON shop.only_a TO echo_verify;" >/dev/null
cv TABLES="shop.only_a"; check "도착에 표 없음" MISMATCH/TARGET_TABLE_MISSING "$(res shop.only_a)"

echo "== 9. 따라잡기 전 → NOT_CAUGHT_UP, 없는 슬롯 → SLOT_MISSING"
q B "ALTER SUBSCRIPTION cv_sub DISABLE;" >/dev/null
q A "INSERT INTO shop.items (id, name) VALUES (4, 'late');" >/dev/null
cv TABLES="shop.items" SLOT=cv_sub CATCHUP_WAIT=2; check "구독 멈춤" UNKNOWN/NOT_CAUGHT_UP "$(res shop.items)"
check "종료 코드" 2 "$RC"
cv TABLES="shop.items" SLOT=no_such_slot; check "없는 슬롯" UNKNOWN/SLOT_MISSING "$(res shop.items)"
q B "ALTER SUBSCRIPTION cv_sub ENABLE;" >/dev/null
wait_eq "SELECT count(*) FROM shop.items"
cv TABLES="shop.items" SLOT=cv_sub; check "다시 붙으면 MATCH" MATCH/- "$(res shop.items)"

echo "== 10. 검사 중 출발이 바뀜 → SOURCE_CHANGED"
( for i in $(seq 1 200); do q A "INSERT INTO demo.seq_write (n) VALUES ($((200000+i)));" >/dev/null 2>&1; sleep 0.05; done ) &
W=$!
cv TABLES="demo.seq_write"; kill $W 2>/dev/null; wait $W 2>/dev/null
check "쓰기 중 검사" UNKNOWN/SOURCE_CHANGED "$(res demo.seq_write)"

echo "== 11. 상한: 행 수 초과 → ROW_LIMIT, 시간 초과 → SOURCE_TIMEOUT"
cv TABLES="demo.seq_write" MAX_ROWS=10; check "MAX_ROWS=10" UNKNOWN/ROW_LIMIT "$(res demo.seq_write)"
q A "CREATE TABLE demo.big (id int PRIMARY KEY, v text); INSERT INTO demo.big SELECT g, repeat('x', 200) FROM generate_series(1, 300000) g;
     GRANT SELECT ON demo.big TO echo_verify;" >/dev/null
q B "CREATE TABLE demo.big (id int PRIMARY KEY, v text); GRANT SELECT ON demo.big TO echo_verify;" >/dev/null
cv TABLES="demo.big" MAX_ROWS=1000000 QUERY_TIMEOUT_MS=50; check "QUERY_TIMEOUT_MS=50" UNKNOWN/SOURCE_TIMEOUT "$(res demo.big)"

echo "== 12. 계획 id 연결"
cv TABLES="shop.items" SLOT=cv_sub PLAN_ID=11111111-1111-4111-8111-111111111111
check "planId" 11111111-1111-4111-8111-111111111111 "$(python3 -I -c 'import json,sys; print(json.loads(sys.argv[1])["planId"])' "$OUT")"
cv TABLES="shop.items"
check "PLAN_ID 없으면 null" None "$(python3 -I -c 'import json,sys; print(json.loads(sys.argv[1])["planId"])' "$OUT")"

echo "== 13. 입력 오류는 아무것도 실행하지 않는다"
cv TABLES="shop.items" PLAN_ID="1'; DROP TABLE shop.items; --"; check "PLAN_ID 주입" 3 "$RC"
cv TABLES="shop.items; DROP TABLE shop.items"; check "표 이름 주입" 3 "$RC"
cv TABLES="shop.items" SLOT="x'; --"; check "슬롯 이름 주입" 3 "$RC"
check "shop.items 그대로" 4 "$(q A 'SELECT count(*) FROM shop.items;')"

echo
echo "결과: 통과 $pass · 실패 $fail"
[[ $fail -eq 0 ]]

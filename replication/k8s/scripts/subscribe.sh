#!/usr/bin/env bash
# 정방향 복제 A→B 를 세운다: B 에 앱 스키마 선반영 → B 가 A 의 echo_pub 을 구독(초기 복사 포함).
# 사용: A_HOST=<A NLB DNS> replication/k8s/scripts/subscribe.sh
source "$(dirname "$0")/common.sh"
: "${A_HOST:?A_HOST=<aws-tokyo/30-expose.yaml 의 NLB DNS>}"
echo "[1] B 스키마 선반영 (echo-demo-app sql/schema.sql 과 같은 DDL)"
pg B <<'SQL'
CREATE SCHEMA IF NOT EXISTS demo;
CREATE TABLE IF NOT EXISTS demo.seq_write (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  n           bigint NOT NULL UNIQUE,
  wrote_at    timestamptz NOT NULL DEFAULT now(),
  written_env text NOT NULL DEFAULT 'unknown'
);
GRANT ALL ON SCHEMA demo TO app_rw;
GRANT ALL ON ALL TABLES IN SCHEMA demo TO app_rw;
ALTER DEFAULT PRIVILEGES IN SCHEMA demo GRANT ALL ON TABLES TO app_rw;
SQL
echo "[1b] 컷오버 결과 표 echo_ops.cutover_runs (A·B 양쪽, 인프라 7.2)"
ops_table_ensure
echo "[2] B: CREATE SUBSCRIPTION echo_sub → $A_HOST (repl_user, TLS require, copy_data)"
kubectl --context "$B_CTX" -n "$NS" exec -i echo-pg-0 -c postgres -- sh -c \
  'echo "CREATE SUBSCRIPTION echo_sub CONNECTION :'"'"'conn'"'"' PUBLICATION echo_pub WITH (copy_data = true);" | \
   psql -X -v ON_ERROR_STOP=1 -U postgres -d app -v conn="host=$0 port=5432 dbname=app user=repl_user password=$REPL_PASSWORD sslmode=require"' "$A_HOST"
echo "[3] 상태"; "$(dirname "$0")/lag.sh"
